!!!        XT: SOLAR LOCAL TIME
!!!        XL: GEOGRAPHIC LONGITUDE (+ EAST)
!!!        PARAM: 2-DIM ARRAY (DOY,F10.7CM)
!!!        DOY     :Day of Year has to run from 1 to 365 (366)
!!!        F10.7cm : F10.7cm solar flux
!!!
!!! Output argument:
!!!        Y: EQUATORIAL VERTICAL DRIFT
