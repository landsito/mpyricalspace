subroutine MODA(IN,YEAR,MONTH,IDAY,IDOY)
!-------------------------------------------------------------------
! !ALCULATES DAY OF YEAR (IDOY) FROM MONTH (MONTH) AND DAY (IDAY)
! IF IN=0, OR MONTH (MONTH) AND DAY (IDAY) FROM DAY OF
! YEAR (IDOY), IF IN>0.
!-------------------------------------------------------------------
    IMPLICIT INTEGER (A-Z)
    DIMENSION     MO(12),MO28(1:12),MO29(1:12)
    DATA MO28/0,31,59,90,120,151,181,212,243,273,304,334/
    DATA MO29/0,31,60,91,121,152,182,213,244,274,305,335/
    IMO=0
    MOBE=0
    IF (mod(YEAR,4).NE.0) THEN
        do i=1,12
          MO(i)=MO28(i)
        end do
    ELSE IF (mod(YEAR,100).NE.0) THEN
        do i=1,12
          MO(i)=MO29(i)
        end do
    ELSE IF (mod(YEAR,400).NE.0) THEN
        do i=1,12
          MO(i)=MO28(i)
        end do
    ELSE
        do i=1,12
          MO(i)=MO29(i)
        end do
    END IF
    IF (IN.GT.0) GOTO 5
    IDOY=MO(MONTH)+IDAY
    RETURN
5   IMO=IMO+1
    MOOLD=MOBE
    IF(IMO.GT.12) GOTO 55
    MOBE=MO(IMO)
    IF(MOBE.LT.IDOY) GOTO 5
55  MONTH=IMO-1
    IDAY=IDOY-MOOLD
   return
end subroutine MODA
