           IF (AED22_28S.LE.0.0D0) AEd22_28S=0.0D0
           AEd22_28=AEd22_28+AEd22_28S
        END DO
        AEd22_28=AEd22_28/7.0D0
        AEd22_28P=AEd22_28-200.0D0
        IF (AEd22_28P.LE.0.0D0) AEd22_28P=0.0D0
!       *************************************************
        IF (AE1_6.GT.300.0D0) THEN
           Alfa=1.0D0
        ELSE IF (AE1_6.GT.200.0D0) THEN
           ALfa=AE1_6/100.0D0-2.0D0
        ELSE
           ALfa=0.0D0
        ENDIF
!       *************************************************
        IF (AE1_12.GE.70.0D0) THEN
           Beta=dexp(-AE1_12/90.0D0)
        ELSE
           Beta=0.46D0
        END IF
!       *************************************************
        PromptVd=0.0D0
        DO J=1,9
           TMP1=Coff1(1,J)*dAEt_30
           TMP2=Coff1(2,J)*dAEt_90
           TMPB=bspl4_ptime(J,SLT)
           PromptVd=PromptVd +(TMP1+TMP2)*TMPB
        END DO
!       *************************************************
        DynamoVd=0.0D0
        DO J=1,9
           TMP1=Coff1(3,J)*AEd1_6
           TMP2=Coff1(4,J)*Alfa*AEd7_12
           TMP3=Coff1(5,J)*Beta*AEd22_28P
           TMPB=bspl4_ptime(J,SLT)
           DynamoVd=DynamoVd+(TMP1+TMP2+TMP3)*TMPB
        END DO
        Vd=PromptVd+DynamoVd
!********************************************************************
!                  15 min time resolution
!********************************************************************
    ELSE
        dAEt_7P5=AE(iP)-AE(iP-1)
        dAEt_30=AE(iP-1)-AE(iP-3)
        dAEt_75=AE(iP-3)-AE(iP-7)
!       *************************************************
        AE1_6=0.0D0
        AEd1_6=0.0D0
        DO i=-4,-24,-1
            AE1_6=AE1_6+AE(iP+i)
            AEd1_6s=AE(iP+i)-130.
            IF (AEd1_6s.LE.0.0) AEd1_6s=0.0
            AEd1_6=AEd1_6+AEd1_6S
        ENDDO
        AE1_6=AE1_6/21.0D0
        AEd1_6=AEd1_6/21.0D0
!       *************************************************
        AEd7_12=0.0D0
        DO i=-28,-48,-1
            AEd7_12s=AE(iP+i)-130.0
            IF (AEd7_12s.LE.0) AEd7_12s=0.0
            AEd7_12=AEd7_12+AEd7_12S
        ENDDO
        AEd7_12=AEd7_12/21.0D0
!       *************************************************
        AE1_12=0.0D0
        DO i=-4,-48,-1
            AE1_12=AE1_12+AE(iP+i)
        END DO
        AE1_12=AE1_12/45.0D0
!       *************************************************
        AEd22_28=0.0D0
        DO i=-88,-112,-1
            AEd22_28s=AE(iP+i)-130.
            IF (AEd22_28s.LE.0) AEd22_28s=0.0
            AEd22_28=AEd22_28+AEd22_28s
        ENDDO
        AEd22_28=AEd22_28/25.0D0
        AEd22_28P=AEd22_28-200.0D0
        IF (AEd22_28P.LE.0.0D0) AEd22_28P=0.0D0
!       *************************************************
        IF (AE1_6.GT.300.0D0) THEN
             Alfa=1.0D0
        ELSE IF (AE1_6.GT.200.0D0) THEN
             ALfa=AE1_6/100.0D0-2.0D0
        ELSE
             ALfa=0.0D0
        ENDIF
!       *************************************************
        IF (AE1_12.GE.70.0D0) THEN
             Beta=dexp(-AE1_12/90.0D0)
        ELSE
             Beta=0.46D0
        END IF
!       *************************************************
        PromptVd=0.0D0
        DO J=1,9
            TMP1=Coff15(1,J)*dAEt_7P5
            TMP2=Coff15(2,J)*dAEt_30
            TMP3=Coff15(3,J)*dAEt_75
            TMPB=bspl4_ptime(J,SLT)
            PromptVd=PromptVd+(TMP1+TMP2+TMP3)*TMPB
        END DO
!       *************************************************
        DynamoVd=0.0D0
        DO J=1,9
            TMP1=Coff15(4,J)*AEd1_6
            TMP2=Coff15(5,J)*Alfa*AEd7_12
            TMP3=Coff15(6,J)*Beta*AEd22_28P
            TMPB=bspl4_ptime(J,SLT)
            DynamoVd=DynamoVd +(TMP1+TMP2+TMP3)*TMPB
        END DO
        Vd=PromptVd+DynamoVd
    ENDIF
return
end subroutine vdrift_storm_model
