     -0.0070,-0.0053,-0.0090, 0.0086, 0.0149, 0.2637, &
     -0.0326,-0.0101, 0.0076, 0.0117, 0.0099, 0.3002, &
     -0.0470,-0.0455,-0.0274, 0.0338, 0.0099, 0.0746/
