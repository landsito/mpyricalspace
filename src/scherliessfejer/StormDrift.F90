! Alfa=0,            AE1_6<200 nT;
!      AE1_6/100-2, 200 nT<AE1_6<200 nT;
!      1,            AE1_6>300 nT;
! Beta=exp(-AE1_12/90),  AE1_12>=70nT;
!      0.46,              AE1_12<70 nT;
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
!*****************************************************
!!        FLAG>0--> 1 h time resolution
!****************************************************
    IF (FLAG.GT.0) THEN
!       *************************************************
        dAEt_30=AE(iP)-AE(iP-1)
        dAEt_90=AE(iP-1)-AE(iP-2)
!       *************************************************
        AE1_6=0.0D0
