real*8 function bspl4_long(i,x1)
!       *************************************************
       implicit real*8 (A-H,O-Z) 
    integer i,order/4/,j,k
       real*8 t_l(0:24)
       real*8 x,b(20,20),x1
       data t_l/0,10,100,190,200,250,280,310, &
               360,370,460,550,560,610,640,670,&
               720,730,820,910,920,970,1000,1030,1080/
       
    x=x1
       if(i.ge.0) then
          if (x.lt.t_l(i-0)) then
         x=x+360
      end if
    end if
    do j=i,i+order-1
       if(x.ge.t_l(j).and.x.lt.t_l(j+1)) then
           b(j,1)=1
       else
           b(j,1)=0
       end if
    end do

    do j=2,order
      do k=i,i+order-j
       b(k,j)=(x-t_l(k))/(t_l(k+j-1)-t_l(k))*b(k,j-1)
       b(k,j)=b(k,j)+(t_l(k+j)-x)/(t_l(k+j)-t_l(k+1))*b(k+1,j-1)
      end do
    end do

    bspl4_long=b(i,order)
   return
end function bspl4_long
