!f2py integer, intent(in) :: FLAG
!f2py integer, intent(in) :: iP
!f2py real*8, intent(in) :: AE
!f2py real*8, intent(in) :: SLT
!f2py real*8, intent(out) :: PromptVd
!f2py real*8, intent(out) :: DynamoVd
!f2py real*8, intent(out) :: Vd

    IMPLICIT REAL*8(A-H,O-Z)
    REAL*8              :: Coff1(1:5,1:9),Coff15(1:6,1:9), AE(1:366*24*4)
    INTEGER             :: FLAG
    DATA Coff1/ 0.0124,-0.0168,-0.0152,-0.0174,-0.0704, &
               -0.0090,-0.0022,-0.0107, 0.0152,-0.0674, &
