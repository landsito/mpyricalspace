/*
 * This module contains routines related to computing the
 * statistics model for given parameter values. The model
 * coefficients must first be generated by the 'eefm' program.
 */

#include <stdio.h>
#include <stdlib.h>
#include <math.h>
#include <string.h>
#include <errno.h>

#include <gsl/gsl_vector.h>
#include <gsl/gsl_math.h>

#include <ndlinear/gsl_multifit_ndlinear.h>

#include "eefm_basis.h"
#include "eefm_calc.h"
#include "eefm_files.h"

static size_t read_coeffs(const char *filename, gsl_vector *x);

/*
 * This structure contains the information for the various
 * model coefficients we can use. The indices here correspond
 * to the EEF_CALC_xxx values in eefm_calc.h
 */
static struct
{
  const char *file_mean_coeffs;
  const char *file_stddev_coeffs;
  size_t n_mean_phi;
  size_t n_mean_t;
  size_t n_mean_s;
  size_t n_mean_euvac;
  size_t n_mean_lunar;
  size_t n_stddev_phi;
  size_t n_stddev_t;
  size_t n_stddev_s;
  size_t n_stddev_euvac;
  size_t n_stddev_lunar;
} model_info[] = {
  {
    FILE_CHAMP_E_MEAN_OUT,
    FILE_CHAMP_E_STDDEV_OUT,
    EEF_MEAN_FIT_N_PHI_DEFAULT,
    EEF_MEAN_FIT_N_T_DEFAULT,
    EEF_MEAN_FIT_N_S_DEFAULT,
    EEF_MEAN_FIT_N_EUVAC_DEFAULT,
    EEF_MEAN_FIT_N_LUNAR_DEFAULT,
    EEF_STDDEV_FIT_N_PHI_DEFAULT,
    EEF_STDDEV_FIT_N_T_DEFAULT,
    EEF_STDDEV_FIT_N_S_DEFAULT,
    EEF_STDDEV_FIT_N_EUVAC_DEFAULT,
    EEF_STDDEV_FIT_N_LUNAR_DEFAULT
  }
};

/*
eefm_calc_alloc()
  Allocate a workspace for computing the model

Inputs: model - EEF_CALC_xxx (specifies which model to use)
                most users will want to specify EEF_CALC_MODEL
                for the default CHAMP model
*/

eefm_calc_workspace *
eefm_calc_alloc(size_t model)
{
  eefm_calc_workspace *w;
  size_t N_mean[EEF_FIT_DIM];
  size_t N_stddev[EEF_FIT_DIM];
  size_t s;

  if (model > 3)
    {
      fprintf(stderr, "eefm_calc_alloc: invalid model\n");
      return 0;
    }

  w = (eefm_calc_workspace *) calloc(1, sizeof(eefm_calc_workspace));
  if (!w)
    return 0;

  N_mean[EEF_IDX_PHI] = model_info[model].n_mean_phi;
  N_mean[EEF_IDX_T] = model_info[model].n_mean_t;
  N_mean[EEF_IDX_S] = model_info[model].n_mean_s;
  N_mean[EEF_IDX_EUVAC] = model_info[model].n_mean_euvac;
  N_mean[EEF_IDX_LUNAR] = model_info[model].n_mean_lunar;

  N_stddev[EEF_IDX_PHI] = model_info[model].n_stddev_phi;
  N_stddev[EEF_IDX_T] = model_info[model].n_stddev_t;
  N_stddev[EEF_IDX_S] = model_info[model].n_stddev_s;
  N_stddev[EEF_IDX_EUVAC] = model_info[model].n_stddev_euvac;
  N_stddev[EEF_IDX_LUNAR] = model_info[model].n_stddev_lunar;

  w->u[EEF_IDX_PHI] = &eefm_basis_phi;
  w->u[EEF_IDX_T] = &eefm_basis_t;
  w->u[EEF_IDX_S] = &eefm_basis_s;
  w->u[EEF_IDX_EUVAC] = &eefm_basis_euvac;
  w->u[EEF_IDX_LUNAR] = &eefm_basis_lunar;

  s = EEF_BASIS_CHAMP;
  if (model == EEF_CALC_OERSTED)
    s = EEF_BASIS_OERSTED;
  else if (model == EEF_CALC_SAC)
    s = EEF_BASIS_SAC;

  w->eefm_basis_mean_p = eefm_basis_alloc(N_mean, s, EEF_BASIS_MEAN);
  w->eefm_basis_stddev_p = eefm_basis_alloc(N_stddev, s, EEF_BASIS_STDDEV);
  if (!w->eefm_basis_mean_p || !w->eefm_basis_stddev_p)
    {
      eefm_calc_free(w);
      return 0;
    }

  w->fit_mean_p = gsl_multifit_ndlinear_alloc(EEF_FIT_DIM,
                                              N_mean,
                                              w->u,
                                              w->eefm_basis_mean_p);
  w->fit_stddev_p = gsl_multifit_ndlinear_alloc(EEF_FIT_DIM,
                                                N_stddev,
                                                w->u,
                                                w->eefm_basis_stddev_p);
  if (!w->fit_mean_p || !w->fit_stddev_p)
    {
      eefm_calc_free(w);
      return 0;
    }

  w->mean_coeffs = gsl_vector_alloc(w->fit_mean_p->n_coeffs);
  w->stddev_coeffs = gsl_vector_alloc(w->fit_stddev_p->n_coeffs);
  if (!w->mean_coeffs || !w->stddev_coeffs)
    {
      eefm_calc_free(w);
      return 0;
    }

  w->x = gsl_vector_alloc(EEF_FIT_DIM);
  if (w->x == 0)
    {
      eefm_calc_free(w);
      return 0;
    }

  s = read_coeffs(model_info[model].file_mean_coeffs, w->mean_coeffs);
  if (!s)
    {
      eefm_calc_free(w);
      fprintf(stderr, "eefm_calc_alloc: Error opening %s\n",
              model_info[model].file_mean_coeffs);
      return 0;
    }

  s = read_coeffs(model_info[model].file_stddev_coeffs,
                  w->stddev_coeffs);
  if (!s)
    {
      eefm_calc_free(w);
      fprintf(stderr, "eefm_calc_alloc: Error opening %s\n",
              model_info[model].file_stddev_coeffs);
      return 0;
    }

  return (w);
} /* eefm_calc_alloc() */

/*
eefm_calc_free()
  Free workspace w
*/

void
eefm_calc_free(eefm_calc_workspace *w)
{
  if (!w)
    return;

  if (w->fit_mean_p)
    gsl_multifit_ndlinear_free(w->fit_mean_p);

  if (w->fit_stddev_p)
    gsl_multifit_ndlinear_free(w->fit_stddev_p);

  if (w->eefm_basis_mean_p)
    eefm_basis_free(w->eefm_basis_mean_p);

  if (w->eefm_basis_stddev_p)
    eefm_basis_free(w->eefm_basis_stddev_p);

  if (w->mean_coeffs)
    gsl_vector_free(w->mean_coeffs);

  if (w->stddev_coeffs)
    gsl_vector_free(w->stddev_coeffs);

  if (w->x)
    gsl_vector_free(w->x);

  free(w);
} /* eefm_calc_free() */

/*
eefm_calc_mean()
  Calculate the EEF mean for given parameters

Inputs: phi - longitude (radians)
        t   - local time (hours)
        s   - season (day of year 0 - 365)
        e   - EUVAC value (W/m^2)
        tau - local lunar time (hours 0 - 24.833)
        w   - workspace

Return: E(phi, t, s, e, tau)
*/

double
eefm_calc_mean(double phi, double t, double s, double e, double tau,
               eefm_calc_workspace *w)
{
  double tau_r; /* lunar time in radians */
  double E;

  if (t < EEF_BASIS_LT_MIN || t > EEF_BASIS_LT_MAX)
    {
      fprintf(stderr,
              "eefm_calc_mean: warning: local time (%f) outside of interval [%f, %f]\n",
              t,
              EEF_BASIS_LT_MIN,
              EEF_BASIS_LT_MAX);
    }

  tau_r = 2.0 * M_PI / 24.83333333 * tau;

  gsl_vector_set(w->x, EEF_IDX_PHI, phi);
  gsl_vector_set(w->x, EEF_IDX_T, t);
  gsl_vector_set(w->x, EEF_IDX_S, s);
  gsl_vector_set(w->x, EEF_IDX_EUVAC, e);
  gsl_vector_set(w->x, EEF_IDX_LUNAR, tau_r);

  E = gsl_multifit_ndlinear_calc(w->x, w->mean_coeffs, w->fit_mean_p);

  return (E);
} /* eefm_calc_mean() */

/*
eefm_calc_stddev()
  Calculate the EEF standard deviation for given parameters

Inputs: phi - longitude (radians)
        t   - local time (hours)
        s   - season (day of year 0 - 365)
        e   - EUVAC value (W/m^2)
        tau - lunar local time (hours 0 to 24.833333)
        w   - workspace

Return: sigma(phi, t, s, e, tau)
*/

double
eefm_calc_stddev(double phi, double t, double s, double e, double tau,
                eefm_calc_workspace *w)
{
  double tau_r;
  double sigma;

  if (t < EEF_BASIS_LT_MIN || t > EEF_BASIS_LT_MAX)
    {
      fprintf(stderr,
              "eefm_calc_stddev: warning: local time (%f) outside of interval [%f, %f]\n",
              t,
              EEF_BASIS_LT_MIN,
              EEF_BASIS_LT_MAX);
    }

  tau_r = 2.0 * M_PI / 24.83333333 * tau;

  gsl_vector_set(w->x, EEF_IDX_PHI, phi);
  gsl_vector_set(w->x, EEF_IDX_T, t);
  gsl_vector_set(w->x, EEF_IDX_S, s);
  gsl_vector_set(w->x, EEF_IDX_EUVAC, e);
  gsl_vector_set(w->x, EEF_IDX_LUNAR, tau_r);

  sigma = gsl_multifit_ndlinear_calc(w->x, w->stddev_coeffs, w->fit_stddev_p);

  return (sigma);
} /* eefm_calc_stddev() */

/********************************************
 *             INTERNAL ROUTINES            *
 ********************************************/

#define MAX_BUF  1000

/*
read_coeffs()
  Read the coefficients in 'filename' and store them in 'x'
*/

static size_t
read_coeffs(const char *filename, gsl_vector *x)
{
  FILE *fp;
  size_t cnt;
  char buf[MAX_BUF];
  int n;
  double y;

  fp = fopen(filename, "r");
  if (!fp)
    {
      perror("fopen");
      return 0;
    }

  cnt = 0;
  while (fgets(buf, MAX_BUF, fp) != NULL)
    {
      if (*buf == '#')
        continue;

      n = sscanf(buf, "%le\n", &y);
      if (n <= 0)
        continue;

      gsl_vector_set(x, cnt++, y);
    }

  fclose(fp);

  return (cnt);
} /* read_coeffs() */
